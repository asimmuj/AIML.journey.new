import numpy as np
data = np.random.normal(50, 10, 1000)
mean=np.mean(data)
variance=np.var(data)
std=np.std(data)
maximum=np.max(data)
minimum=np.min(data)
below_mean = np.sum(data < mean)
above_mean = np.sum(data > mean)
equal_mean = np.sum(data == mean)
print(mean)
print(variance)
print(std)
print(maximum)
print(minimum)
print(below_mean)
print(above_mean)
print(equal_mean)